/**
 * Sites for one organisation, capped at the number the account is licensed for
 * (a roster can legitimately be shorter than `gym.sites`).
 */
export function sitesForGym(gymId: string, siteCount: number): GymSite[] {
  const roster = SITES_BY_GYM[gymId] ?? DEFAULT_SITES;
  return roster.slice(0, Math.max(0, siteCount));
}

export function findGym(gymId: string): Gym | undefined {
  return GYMS.find((gym) => gym.id === gymId);
}
